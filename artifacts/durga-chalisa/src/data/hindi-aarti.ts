export type VerseLine = {
  id: number;
  type: 'doha' | 'chaupai';
  text: string;
};

const makeLines = (lyrics: string): VerseLine[] =>
  lyrics
    .trim()
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((text, id) => ({
      id,
      type: text.includes('ॐ जयो जयो') || text.includes('माम् पाहि') ? 'doha' : 'chaupai',
      text,
    }));

